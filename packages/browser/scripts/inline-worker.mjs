#!/usr/bin/env node
// Inline the IIFE worker bundle into src/worker/worker-source.ts as a string
// literal so the main tsup build resolves WORKER_SOURCE like a regular module.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = join(here, "..");
const workerPath = join(pkgRoot, "dist/.worker-build/worker.js");
const outPath = join(pkgRoot, "src/worker/worker-source.ts");

const workerSrc = readFileSync(workerPath, "utf8");

const escaped = JSON.stringify(workerSrc);

const banner = `// AUTO-GENERATED by scripts/inline-worker.mjs — do not edit by hand.\n` +
  `// Stub is checked in; CI fails if \`pnpm build\` produces a diff here.\n` +
  `// The worker bundles fflate and @rrweb/packer (both MIT): see THIRD_PARTY_NOTICES.md.\n`;

writeFileSync(outPath, `${banner}export const WORKER_SOURCE = ${escaped};\n`);

const sizeKb = (new TextEncoder().encode(workerSrc).byteLength / 1024).toFixed(2);
console.log(`[inline-worker] wrote ${outPath} (${sizeKb} kB worker source)`);
