// Writes lib/src/instrumentation/framework_widgets.g.dart: every public
// StatelessWidget and StatefulWidget that package:flutter exports.
//
// A tap's component path names the app's own widgets (HomeScreen > Card >
// Button), the way the RN SDK names an app's components and skips host views.
// A Flutter release build has no record of where a widget class was declared,
// so the walk compares a widget's runtimeType against this list by identity:
// an app's own `Card` stays in the path while Material's is left out, and the
// comparison survives --obfuscate. Generic widgets are listed by name instead,
// since `ValueListenableBuilder<int>` is a different Type from the raw class.
// A widget missing from the list (a newer Flutter's) only adds a framework
// segment to some paths; nothing breaks.
//
// Run from packages/flutter after a Flutter upgrade:
//
//   dart run tool/framework_widgets.dart
import 'dart:io';

void main() {
  final flutter = Process.runSync('flutter', ['--version', '--machine']);
  final root = RegExp(
    r'"flutterRoot":\s*"([^"]+)"',
  ).firstMatch('${flutter.stdout}')![1]!;
  final version = RegExp(
    r'"frameworkVersion":\s*"([^"]+)"',
  ).firstMatch('${flutter.stdout}')![1]!;

  // Every public class and what it extends, across the libraries apps build with.
  final parents = <String, String>{};
  final declaration = RegExp(
    r'^(?:abstract\s+|base\s+|final\s+|sealed\s+)*class\s+([A-Z]\w*)(?:<[^{]*?>)?\s+extends\s+(\w+)',
    multiLine: true,
  );
  for (final library in ['widgets', 'material', 'cupertino']) {
    final dir = Directory('$root/packages/flutter/lib/src/$library');
    for (final file in dir.listSync(recursive: true).whereType<File>()) {
      if (!file.path.endsWith('.dart')) continue;
      for (final match in declaration.allMatches(file.readAsStringSync())) {
        parents[match[1]!] = match[2]!;
      }
    }
  }

  bool isComposite(String name, [int depth = 0]) {
    if (name == 'StatelessWidget' || name == 'StatefulWidget') return true;
    final parent = parents[name];
    return parent != null && depth < 20 && isComposite(parent, depth + 1);
  }

  final generic = <String>{};
  final genericDeclaration = RegExp(
    r'^(?:abstract\s+|base\s+|final\s+|sealed\s+)*class\s+([A-Z]\w*)<',
    multiLine: true,
  );
  for (final library in ['widgets', 'material', 'cupertino']) {
    final dir = Directory('$root/packages/flutter/lib/src/$library');
    for (final file in dir.listSync(recursive: true).whereType<File>()) {
      if (!file.path.endsWith('.dart')) continue;
      for (final match in genericDeclaration.allMatches(
        file.readAsStringSync(),
      )) {
        generic.add(match[1]!);
      }
    }
  }

  final composites = parents.keys.where(isComposite).toSet();
  var types = (composites.difference(generic).toList()..sort());
  final names = (composites.intersection(generic).toList()..sort());
  const outPath = 'lib/src/instrumentation/framework_widgets.g.dart';

  String render() {
    final out = StringBuffer()
      ..writeln(
        '// Generated by tool/framework_widgets.dart from Flutter $version. Do not edit.',
      )
      ..writeln('// ignore_for_file: deprecated_member_use')
      ..writeln()
      ..writeln("import 'package:flutter/cupertino.dart';")
      ..writeln("import 'package:flutter/material.dart';")
      ..writeln()
      ..writeln(
        '/// The public composite widgets package:flutter exports, which a',
      )
      ..writeln('/// component path leaves out. Compared by identity.')
      ..writeln('const frameworkWidgetTypes = <Type>{');
    for (final name in types) {
      out.writeln('  $name,');
    }
    out
      ..writeln('};')
      ..writeln()
      ..writeln(
        '/// The generic ones, compared by their name without type arguments.',
      )
      ..writeln('const frameworkGenericWidgetNames = <String>{');
    for (final name in names) {
      out.writeln("  '$name',");
    }
    out.writeln('};');
    return '$out';
  }

  // Some declared classes are not exported; drop whatever the analyzer can't
  // resolve and write again.
  File(outPath).writeAsStringSync(render());
  final analysis = Process.runSync('flutter', ['analyze', '--no-pub', outPath]);
  final undefined = RegExp(
    r"Undefined name '(\w+)'",
  ).allMatches('${analysis.stdout}').map((m) => m[1]!).toSet();
  types = [
    for (final t in types)
      if (!undefined.contains(t)) t,
  ];
  File(outPath).writeAsStringSync(render());
  Process.runSync('dart', ['format', outPath]);
  stdout.writeln(
    '${types.length} framework widget types and ${names.length} generic names '
    'from Flutter $version',
  );
}
